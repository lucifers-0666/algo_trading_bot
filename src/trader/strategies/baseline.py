"""Deterministic Baseline Swing Strategy for Indian Equities.
Implements an explainable trend-pullback daily swing strategy using SMA, RSI, ATR, and volume confirmation.
Signals are evaluated exclusively on completed candle close (t) for simulated execution at next open (t+1).
"""

from enum import Enum
from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field
from datetime import datetime
import pandas as pd

from trader.domain.models import Candle, IST
from trader.features.technical import candles_to_dataframe, compute_all_indicators


class SignalType(str, Enum):
    BUY = "BUY"
    SELL = "SELL" # Exit signal for open long position
    HOLD = "HOLD"


class StrategySignal(BaseModel):
    """Actionable signal generated by the strategy engine."""
    symbol: str
    signal_type: SignalType
    timestamp: datetime
    reference_close: float
    suggested_stop_loss: Optional[float] = None
    suggested_target: Optional[float] = None
    reason: str
    metrics: Dict[str, float] = Field(default_factory=dict)


class BaselineSwingStrategy:
    """Configurable trend-following pullback strategy."""

    def __init__(
        self,
        sma_fast: int = 20,
        sma_slow: int = 50,
        rsi_period: int = 14,
        rsi_min: float = 45.0,
        rsi_max: float = 65.0,
        atr_period: int = 14,
        stop_atr_mult: float = 2.0,
        target_atr_mult: float = 4.0,
        min_price: float = 20.0,
        min_turnover_inr: float = 5000000.0,
        max_holding_candles: int = 15,
    ):
        self.sma_fast = sma_fast
        self.sma_slow = sma_slow
        self.rsi_period = rsi_period
        self.rsi_min = rsi_min
        self.rsi_max = rsi_max
        self.atr_period = atr_period
        self.stop_atr_mult = stop_atr_mult
        self.target_atr_mult = target_atr_mult
        self.min_price = min_price
        self.min_turnover_inr = min_turnover_inr
        self.max_holding_candles = max_holding_candles

    def evaluate_entry(self, df_ind: pd.DataFrame) -> Optional[StrategySignal]:
        """Evaluates entry condition on the latest completed candle."""
        if len(df_ind) < max(self.sma_slow + 5, 55):
            return None

        curr = df_ind.iloc[-1]
        c = float(curr["close"])
        low = float(curr["low"])
        vol = float(curr["volume"])
        ts = curr["timestamp"]
        sym = str(curr["symbol"]).upper()

        # Indicator values
        s_fast = float(curr["sma_20"])
        s_slow = float(curr["sma_50"])
        rsi = float(curr["rsi_14"])
        atr = float(curr["atr_14"])
        vol_avg = float(curr["vol_sma_20"])
        turnover = float(curr.get("turnover_sma_20", curr.get("turnover", 0.0)))

        # 1. Liquidity Guard
        if c < self.min_price or turnover < self.min_turnover_inr:
            return None

        # 2. Trend Confirmation: Close > SMA20 > SMA50
        trend_ok = (c > s_fast) and (s_fast > s_slow)

        # 3. Pullback / Support Test: Low touched near SMA20, but Close bounced above
        pullback_ok = (low <= s_fast * 1.015) and (c > s_fast)

        # 4. Momentum Filter: RSI within healthy sweet spot
        rsi_ok = self.rsi_min <= rsi <= self.rsi_max

        # 5. Volume Filter: Volume is above average
        vol_ok = vol >= vol_avg * 0.95

        if trend_ok and pullback_ok and rsi_ok and vol_ok:
            stop_loss = round(c - (self.stop_atr_mult * atr), 2)
            target = round(c + (self.target_atr_mult * atr), 2)
            reason = (
                f"Trend-pullback entry: Close ({c:.2f}) > SMA20 ({s_fast:.2f}) > SMA50 ({s_slow:.2f}), "
                f"Low touched SMA20, RSI={rsi:.1f}, Volume={vol:,.0f} >= Avg={vol_avg:,.0f}"
            )
            return StrategySignal(
                symbol=sym,
                signal_type=SignalType.BUY,
                timestamp=ts,
                reference_close=c,
                suggested_stop_loss=stop_loss,
                suggested_target=target,
                reason=reason,
                metrics={
                    "close": c,
                    "sma_20": s_fast,
                    "sma_50": s_slow,
                    "rsi_14": rsi,
                    "atr_14": atr,
                    "stop_loss": stop_loss,
                    "target": target,
                },
            )
        return None

    def evaluate_exit(
        self,
        df_ind: pd.DataFrame,
        entry_price: float,
        stop_loss: float,
        target: Optional[float],
        holding_candles: int,
    ) -> Optional[StrategySignal]:
        """Evaluates exit conditions for an existing active position."""
        if df_ind.empty:
            return None

        curr = df_ind.iloc[-1]
        c = float(curr["close"])
        low = float(curr["low"])
        high = float(curr["high"])
        s_slow = float(curr.get("sma_50", 0.0))
        ts = curr["timestamp"]
        sym = str(curr["symbol"]).upper()

        # 1. Stop loss hit
        if low <= stop_loss:
            return StrategySignal(
                symbol=sym,
                signal_type=SignalType.SELL,
                timestamp=ts,
                reference_close=c,
                reason=f"Stop loss triggered: Low ({low:.2f}) <= Stop ({stop_loss:.2f})",
                metrics={"exit_price": stop_loss, "pnl_pct": (stop_loss - entry_price) / entry_price},
            )

        # 2. Target hit
        if target is not None and high >= target:
            return StrategySignal(
                symbol=sym,
                signal_type=SignalType.SELL,
                timestamp=ts,
                reference_close=c,
                reason=f"Profit target triggered: High ({high:.2f}) >= Target ({target:.2f})",
                metrics={"exit_price": target, "pnl_pct": (target - entry_price) / entry_price},
            )

        # 3. Trend break (Close below SMA 50)
        if s_slow > 0 and c < s_slow:
            return StrategySignal(
                symbol=sym,
                signal_type=SignalType.SELL,
                timestamp=ts,
                reference_close=c,
                reason=f"Trend break exit: Close ({c:.2f}) < SMA50 ({s_slow:.2f})",
                metrics={"exit_price": c, "pnl_pct": (c - entry_price) / entry_price},
            )

        # 4. Time-based max holding period
        if holding_candles >= self.max_holding_candles:
            return StrategySignal(
                symbol=sym,
                signal_type=SignalType.SELL,
                timestamp=ts,
                reference_close=c,
                reason=f"Max holding period reached: {holding_candles} candles >= {self.max_holding_candles}",
                metrics={"exit_price": c, "pnl_pct": (c - entry_price) / entry_price},
            )

        return None

